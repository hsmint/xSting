"""Collect labeled sessions into data/dataset/{images,labels}/{train,val,test} and write data.yaml.

usage: python3 tools/build_dataset.py [--split block|session] [--val 0.2]
  block   (pilot): the last --val share of every session goes to val (consecutive photos stay
          together, so near-duplicates do not straddle train and val)
  session : whole sessions go to val (every 1/val-th session) -- use once there are many sessions
Sessions whose scene name starts with 'test_' always go to test (shoot them on another day).
Photos listed in <session>/rejected.txt or still in needs_class.txt are skipped. The dataset folder is rebuilt every run.
"""
import argparse
import shutil
from collections import Counter
from pathlib import Path

from capture import CLASSES

DATA = Path(__file__).resolve().parents[1] / 'data'


def main():
    ap = argparse.ArgumentParser(description='build the YOLO-seg dataset')
    ap.add_argument('--split', choices=['block', 'session'], default='block')
    ap.add_argument('--val', type=float, default=0.2)
    a = ap.parse_args()
    sessions = sorted(p for p in (DATA / 'labeled').iterdir() if (p / 'labels').is_dir())
    if not sessions:
        raise SystemExit('data/labeled에 세션이 없음 (auto_label.py 먼저)')
    out = DATA / 'dataset'
    for d in ('images', 'labels'):
        shutil.rmtree(out / d, ignore_errors=True)
        for s in ('train', 'val', 'test'):
            (out / d / s).mkdir(parents=True)
    stats = {s: Counter() for s in ('train', 'val', 'test')}
    imgs = Counter()
    trainval = [s for s in sessions if not s.name.split('_', 2)[-1].startswith('test_')]
    for k, sess in enumerate(sessions):
        rejected = set((sess / 'rejected.txt').read_text().split()) if (sess / 'rejected.txt').exists() else set()
        pending = set((sess / 'needs_class.txt').read_text().split()) if (sess / 'needs_class.txt').exists() else set()
        if pending:
            print(f'{sess.name}: 클래스 미지정 {len(pending)}장 제외 (review_labels.py로 지정)')
        rejected |= pending
        photos = [p for p in sorted((sess / 'images').glob('*.jpg')) if p.name not in rejected]
        scene = sess.name.split('_', 2)[-1]
        for i, p in enumerate(photos):
            if scene.startswith('test_'):
                split = 'test'
            elif a.split == 'session':
                split = 'val' if trainval.index(sess) % round(1 / a.val) == round(1 / a.val) - 1 else 'train'
            else:
                split = 'val' if i >= len(photos) * (1 - a.val) else 'train'
            name = f'{sess.name}__{p.name}'
            shutil.copy2(p, out / 'images' / split / name)
            lab = (sess / 'labels' / f'{p.stem}.txt').read_text()
            (out / 'labels' / split / f'{Path(name).stem}.txt').write_text(lab)
            imgs[split] += 1
            for line in lab.splitlines():
                stats[split][CLASSES[int(line.split()[0])]] += 1
    (out / 'data.yaml').write_text(
        '# generated by tools/build_dataset.py\n'
        f'path: {out}\ntrain: images/train\nval: images/val\ntest: images/test\n\nnames:\n'
        + ''.join(f'  {i}: {c}\n' for i, c in enumerate(CLASSES)), encoding='utf-8')
    for s in ('train', 'val', 'test'):
        print(f'{s:5s}: 사진 {imgs[s]:4d}, 물체 ' + ', '.join(f'{c} {stats[s][c]}' for c in CLASSES))
    print(f'→ {out / "data.yaml"}')


if __name__ == '__main__':
    main()
